import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { afterAll, afterEach, beforeAll, beforeEach, describe, expect, it } from 'vitest'
import { IntakeSandbox, compileIntakeWorkers, opsOf, snapshotFiles, zip, requestWorker, resources, redigest } from '../helpers/intake-workers'
import { makeZip } from '../helpers/containers'

let compiled: string, workers: Awaited<ReturnType<typeof compileIntakeWorkers>>, s: IntakeSandbox
beforeAll(async () => { compiled = fs.mkdtempSync(path.join(os.tmpdir(), 'avca-e2e-build-')); workers = await compileIntakeWorkers(compiled) })
beforeEach(() => { s = new IntakeSandbox(workers) })
afterEach(() => s.close())
afterAll(() => { fs.rmSync(compiled, { recursive: true, force: true }) })
const contents = (plan: Awaited<ReturnType<IntakeSandbox['plan']>>) => opsOf(plan).map(op => fs.readFileSync(path.join(s.library, op.targetRelPath), 'utf8')).sort()

describe('M9 content matrix through production planning and execution workers', () => {
  it('#1 names do not authorize a skip; identical archive contents do, with durable evidence', async () => {
    s.file('same/data.txt', 'payload'); await zip(path.join(s.source, 'same.zip'), [['renamed.txt', 'payload']])
    const before = snapshotFiles(s.source), plan = await s.plan()
    expect(plan.skips.filter(x => x.scope === 'archive')).toHaveLength(1)
    expect(plan.skips[0].evidence).toMatchObject({ coveredCount: 1, totalCount: 1 })
    await s.commit(plan)
    expect(contents(plan)).toEqual(['payload'])
    const provenance = s.db.prepare('SELECT detail FROM source_occurrence WHERE plan_id=?').all(plan.id)
    expect(provenance).toHaveLength(2); expect(JSON.stringify(provenance)).toContain('crc32')
    expect(snapshotFiles(s.source)).toEqual(before)
  })
  it('#2/#3 garbled member names and extra directory shells preserve all bytes', async () => {
    s.file('散目录/外壳/文字.url', 'payload')
    await zip(path.join(s.source, 'download.zip'), [['garbled-文件名/readme.txt', 'payload']])
    const plan = await s.plan(); await s.commit(plan)
    expect(plan.skips.some(x => x.scope === 'archive' && x.evidence.coveredCount === 1)).toBe(true)
    expect(contents(plan)).toEqual(['payload'])
  })
  it('#7 identical archives in separate directories publish one payload and both occurrences', async () => {
    const archive = await zip(path.join(s.source, 'a/one.zip'), [['file.txt', 'one']])
    fs.mkdirSync(path.join(s.source, 'b')); fs.copyFileSync(archive, path.join(s.source, 'b/two.zip'))
    const plan = await s.plan(); await s.commit(plan)
    expect(opsOf(plan)).toHaveLength(1); expect(contents(plan)).toEqual(['one'])
    expect(plan.skips.some(x => x.reason === 'duplicate-of-kept-archive')).toBe(true)
    expect(s.db.prepare('SELECT count(*) n FROM source_occurrence').get()).toEqual({ n: 2 })
  })
  it('#8 three loose copies publish one physical blob with three provenance rows', async () => {
    for (const dir of ['a', 'b', 'c']) s.file(dir + '/same.txt', 'same')
    const plan = await s.plan(); await s.commit(plan)
    expect(s.db.prepare('SELECT count(*) n FROM content_blob').get()).toEqual({ n: 1 })
    expect(s.db.prepare('SELECT count(*) n FROM source_occurrence').get()).toEqual({ n: 3 })
    expect(opsOf(plan).filter(o => o.action === 'copy')).toHaveLength(1)
  })
  it('#9 repeated equal ZIP members require two logical occurrences, not a Set', async () => {
    s.file('loose/same.txt', 'same'); await zip(path.join(s.source, 'twice.zip'), [['one.txt', 'same'], ['two.txt', 'same']])
    const plan = await s.plan(); await s.commit(plan)
    expect(plan.skips.filter(x => x.scope === 'archive')).toEqual([])
    // The loose path and the two paths in the complete container tree remain logical references.
    expect(opsOf(plan)).toHaveLength(3); expect(contents(plan)).toEqual(['same', 'same', 'same'])
    expect(s.db.prepare('SELECT count(*) n FROM content_blob').get()).toEqual({ n: 1 })
  })
  it('#10 renamed RAR uses the real decoder; a truncated RAR remains raw with a warning', async () => {
    const original = path.resolve('tests/fixtures/rar/WithComment.rar'), intact = s.file('renamed.zip', fs.readFileSync(original))
    const a = await s.plan(intact); await s.commit(a)
    expect(opsOf(a)).toHaveLength(2); expect(opsOf(a).some(o => /\.zip$/i.test(o.targetRelPath))).toBe(false)
    const bad = s.file('cut.rar', fs.readFileSync(original).subarray(0, 12)), b = await s.plan(bad)
    expect(b.warnings.join()).toContain('opaque'); expect(b.skips).toEqual([])
    await s.commit(b); expect(fs.readFileSync(path.join(s.library, opsOf(b)[0].targetRelPath))).toEqual(fs.readFileSync(bad))
  })
  it('#11 depth beyond the real worker budget preserves the inner container and sibling', async () => {
    let bytes = Buffer.from('leaf')
    for (let i = 0; i < 10; i++) { const file = await zip(path.join(s.root, `level-${i}.zip`), [[i ? 'inner.zip' : 'leaf.txt', bytes]]); bytes = fs.readFileSync(file) }
    const archive = s.file('deep.zip', bytes), plan = await s.plan(archive)
    expect(plan.warnings.join()).toContain('budget-depth'); expect(plan.skips).toEqual([])
    await s.commit(plan); expect(opsOf(plan).length).toBeGreaterThan(0)
    expect(opsOf(plan).some(op => /\.zip$/i.test(op.targetRelPath))).toBe(true)
  })
  it('#11 real 7z expansion budget rejects before materialization (scaled giant-container boundary)', async () => {
    s.file('large.bin', Buffer.alloc(1024 * 1024, 1))
    const archive = makeZip(s.source, path.join(s.root, 'giant.7z'), ['large.bin'], undefined, [], '7z')
    const result = await s.fault({ type: 'closure', source: archive, budget: { maxFileBytes: 1024 } })
    expect(result.opaque).toBe(true); expect(result.warnings.join()).toContain('budget-file')
    expect(result.leaves[0].localPath).toBe(archive)
    expect(fs.readdirSync(path.join(s.root, 'fault-cache/objects'))).toEqual([])
  })
  it('#12 nested passwords address the actual inner entity; decline retains that container', async () => {
    s.file('secret.txt', 'secret')
    const inner = makeZip(s.source, path.join(s.root, 'inner.7z'), ['secret.txt'], undefined, ['-pinner', '-mhe=on'], '7z')
    const outerDir = path.join(s.root, 'outer-input'); fs.mkdirSync(outerDir); fs.copyFileSync(inner, path.join(outerDir, 'inner.7z'))
    const outer = makeZip(outerDir, path.join(s.root, 'outer.7z'), ['inner.7z'], undefined, ['-pouter', '-mhe=on'], '7z')
    const prompted: string[] = [], plan = await s.plan(outer, { password: file => { prompted.push(file); return file === outer ? 'outer' : 'inner' } })
    expect(prompted).toHaveLength(2); expect(prompted[0]).toBe(outer); expect(prompted[1]).not.toBe(outer)
    await s.commit(plan); expect(contents(plan)).toEqual(['secret'])
    const freshOuter = path.join(s.root, 'declined.7z'); fs.copyFileSync(outer, freshOuter)
    // A new namespace prevents a successful prior cache from bypassing this password path.
    const other = new IntakeSandbox(workers)
    try {
      const declined = await other.plan(freshOuter, { password: file => file === freshOuter ? 'outer' : null })
      expect(declined.warnings.join()).toContain('password-declined'); expect(declined.skips).toEqual([])
      await other.commit(declined)
      expect(fs.readFileSync(path.join(other.library, opsOf(declined)[0].targetRelPath))).toEqual(fs.readFileSync(inner))
    } finally { other.close() }
  })
  it('#18 illegal and colliding Windows member names are sanitized while original paths survive', async () => {
    const archive = await zip(path.join(s.root, 'illegal.zip'), [[' folder|/a?.txt', 'first'], [' folder|/a*.txt', 'second']])
    const plan = await s.plan(archive); await s.commit(plan)
    expect(new Set(opsOf(plan).map(o => o.targetRelPath.toLowerCase())).size).toBe(2)
    expect(opsOf(plan).every(o => !/[|?*]/.test(o.targetRelPath))).toBe(true)
    expect(plan.occurrences.map(o => o.relPath)).toContain(' folder|/a?.txt')
    expect(contents(plan)).toEqual(['first', 'second'])
  })
  it('#19 same relative pathname with different content keeps both versions and diagnoses conflict', async () => {
    const archive = await zip(path.join(s.root, 'versions.zip'), [['same.txt', 'version-one'], ['same.txt', 'version-two']])
    const plan = await s.plan(archive); await s.commit(plan)
    expect(contents(plan)).toEqual(['version-one', 'version-two'])
    expect(opsOf(plan).map(o => o.targetRelPath.toLowerCase())).toHaveLength(2)
    expect(new Set(opsOf(plan).map(o => o.targetRelPath.toLowerCase())).size).toBe(2)
    expect(plan.warnings.join()).toMatch(/conflict|collision|不一致|冲突/)
  })
  it('#20 union coverage across directories supplements only the missing leaf', async () => {
    s.file('a/a.txt', 'aaa'); s.file('b/b.txt', 'bbb')
    await zip(path.join(s.source, 'combined.zip'), [['x.txt', 'aaa'], ['y.txt', 'bbb'], ['z.txt', 'ccc']])
    const plan = await s.plan(); await s.commit(plan)
    expect(plan.extracts.flatMap(e => e.members)).toHaveLength(1)
    expect(new Set(contents(plan))).toEqual(new Set(['aaa', 'bbb', 'ccc']))
    expect(s.db.prepare('SELECT count(*) n FROM content_blob').get()).toEqual({ n: 3 })
  })
  it('#21 competing complete sources select a stable loose representative across real worker restarts', async () => {
    s.file('same/a.txt', 'payload'); s.file('other/a.txt', 'payload')
    await zip(path.join(s.source, 'same.zip'), [['a.txt', 'payload']])
    const a = await s.plan(), b = await s.plan()
    expect(JSON.stringify(a)).toBe(JSON.stringify(b))
    expect(a.skips.find(x => x.scope === 'archive')?.evidence.matches[0].coveringRelPath).toContain('same/')
    await s.commit(a); expect(s.db.prepare('SELECT count(*) n FROM content_blob').get()).toEqual({ n: 1 })
  })
  it('#22 a single nested ZIP uses the normalized route regardless of autoExtract', async () => {
    const inner = await zip(path.join(s.root, 'inner.zip'), [['member.txt', 'member']])
    const outer = await zip(path.join(s.root, 'outer.zip'), [['inner.zip', fs.readFileSync(inner)]])
    const a = await s.plan(outer, { extract: false }), b = await s.plan(outer, { extract: true })
    expect(b).toEqual(a); await s.commit(a)
    expect(contents(a)).toEqual(['member']); expect(opsOf(a).some(o => /\.zip$/i.test(o.targetRelPath))).toBe(false)
  })
  it('#24 junction loops and a text file named zip never become archive contents', async () => {
    s.file('fake.zip', '15 byte text!!!'); s.file('real.txt', 'real')
    fs.symlinkSync(s.source, path.join(s.source, 'loop'), 'junction')
    const plan = await s.plan()
    expect(plan.blocked.some(b => b.reason.includes('reparse'))).toBe(true)
    expect(plan.warnings.join()).toContain('extension-mismatch')
    expect(opsOf(plan).some(o => o.originalRelPath === 'fake.zip')).toBe(true)
    s.persist(plan); await expect(s.execute(plan)).rejects.toThrow('blocked')
    expect(fs.readdirSync(s.library)).toEqual([])
  })
  it('#25 empty files and noise are copied; an empty ZIP is retained as an opaque empty source', async () => {
    s.file('empty.txt', ''); s.file('Thumbs.db', 'thumbnail-data'); s.file('desktop.ini', 'config')
    await zip(path.join(s.source, 'empty.zip'), [])
    const plan = await s.plan(); await s.commit(plan)
    expect(opsOf(plan).map(o => o.originalRelPath)).toEqual(expect.arrayContaining(['empty.txt', 'Thumbs.db', 'desktop.ini']))
    expect(opsOf(plan).find(o => o.originalRelPath === 'empty.txt')?.key).toEqual({ size: 0, crc32: 0 })
    expect(contents(plan)).toContain('thumbnail-data')
    expect(opsOf(plan).some(o => o.originalRelPath === 'empty.zip')).toBe(true)
  })
  it('#29/#30 post-copy classification consumes real readme and source parents instead of planner category', async () => {
    s.file('data.fbx', 'mesh'); s.file('readme.txt', '衣服 outfit clothing https://booth.pm/ja/items/1234567')
    const plan = await s.plan(); plan.units[0].classification.units[0].category = 'wrong-planner-category'; redigest(plan)
    await s.commit(plan)
    const final = await s.fault({ type: 'classify', planId: plan.id })
    expect(final.ingest.sourceDirChain).toEqual(path.dirname(s.source).split(/[\\/]/).filter(x => x && !/^[a-z]:$/i.test(x)).slice(-4))
    expect(final.ingest.sourceDirChain).not.toContain('Atrium素材库')
    expect(final.ingest.rawName).toBe('商品'); expect(final.ingest.stagingPath).toBe(plan.units[0].libraryPath)
    expect(final.ingest.metadata.readmeText).toContain('outfit')
    expect(s.db.prepare('SELECT category FROM asset').get()).toEqual({ category: final.classification.units[0].category })
    expect(final.classification.units[0].category).not.toBe('wrong-planner-category')
  })
  it('#16 health uses loose representatives through the production health worker without source changes', async () => {
    const loose = s.file('loose/file.txt', 'payload'), archive = await zip(path.join(s.source, 'different.zip'), [['renamed.txt', 'payload']])
    const before = snapshotFiles(s.source), dir = path.dirname(loose)
    const message = await requestWorker<any>(workers.health, { items: [{ path: archive, sizeBytes: fs.statSync(archive).size, entries: 1, isDir: false }, { path: dir, sizeBytes: 7, entries: 1, isDir: true }], options: { cacheNamespace: s.dbFile, extraBackendDirs: [path.join(resources, 'bin')] } }, ['result'])
    expect(message.result.items.map((i: any) => i.path)).toEqual([dir])
    expect(message.result.items[0].coveredArchives[0].evidence).toMatchObject({ coveredCount: 1, totalCount: 1 })
    expect(snapshotFiles(s.source)).toEqual(before)
  })
})
